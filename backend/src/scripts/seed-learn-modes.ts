async function main() {
  await connectDB()
  for (const s of scenarios) {
    await DetectiveScenario.findOneAndUpdate({ slug: s.slug }, s, { upsert: true, new: true })
    console.log('upserted detective', s.slug)
  }
  for (const r of recipes) {
    await MashupRecipe.findOneAndUpdate({ slug: r.slug }, r, { upsert: true, new: true })
    console.log('upserted mashup', r.slug)
  }
  console.log(`done — ${scenarios.length} detective, ${recipes.length} mashup`)
  process.exit(0)
}

main().catch(err => {
  console.error(err)
  process.exit(1)
})
