type Diff = 'easy' | 'medium' | 'hard'
type Mode = 'identify' | 'detect' | 'explain'

function det(
  order: number,
  slug: string,
  title: string,
  mode: Mode,
  difficulty: Diff,
  stem: string,
  answer: string,
  choices: string[],
  explanation: string,
) {
  return {
    slug,
    title,
    mode,
    difficulty,
    stem,
    answer,
    choices,
    explanation,
    status: 'published' as const,
    order,
  }
}

function mash(
  order: number,
  slug: string,
  title: string,
  difficulty: Diff,
  summary: string,
  constraints: string[],
  problemLabels: string[],
) {
  return {
    slug,
    title,
    difficulty,
    summary,
    constraints,
    problemLabels,
    status: 'published' as const,
    order,
  }
}

