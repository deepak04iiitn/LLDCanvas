type EventType = 'requirement' | 'scale' | 'failure' | 'business' | 'team' | 'time' | 'constraint' | 'boss'

interface HealthDelta {
  coupling?: number
  cohesion?: number
  extensibility?: number
  complexity?: number
  reliability?: number
  debt?: number
}

interface DecisionOption {
  id: 'A' | 'B' | 'C'
  label: string
  description: string
  healthDelta: HealthDelta
  tags: string[]
  consequence: string
}

interface StageEvent {
  type: EventType
  title: string
  description: string
  icon: string
  decisions?: DecisionOption[]
  requiresDesign: boolean
  hint?: string
  successCriteria?: string
}

interface Stage {
  id: string
  order: number
  title: string
  event: StageEvent
  isBoss: boolean
  isCheckpoint: boolean
  failureExplanation?: string
}

interface RoguelikeScenario {
  slug: string
  title: string
  icon: string
  description: string
  systemContext: string
  initialRequirement: string
  difficulty: 'hard'
  modes: string[]
  stages: Stage[]
  initialConstraints: {
    complexityBudget: number
    engineeringHours: number
    teamSize: number
    infraBudget: number
    maxStructuralChanges: number
    expectedUsers: string
  }
  tags: string[]
  status: 'published'
  order: number
  estimatedMinutes: number
}

